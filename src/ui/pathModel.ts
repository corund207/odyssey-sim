// persistence
// ---------------------------------------------------------------------------

export interface SavedPath {
  points: PathPoint[];
  timeout: number;
}

const isNum = (v: unknown): v is number => typeof v === 'number' && Number.isFinite(v);

/** validate untrusted JSON (e.g. from localStorage); returns null if unusable */
export function parseSavedPath(raw: string | null): SavedPath | null {
  if (!raw) return null;
  try {
    const data = JSON.parse(raw) as { points?: unknown; timeout?: unknown };
    if (!Array.isArray(data.points)) return null;
    const points: PathPoint[] = [];
    for (const item of data.points as Partial<PathPoint>[]) {
      if (!item || !isNum(item.x) || !isNum(item.y)) return null;
      points.push({
        x: clampField(item.x),
        y: clampField(item.y),
        kind: item.kind === 'pose' ? 'pose' : 'point',
        theta: isNum(item.theta) ? item.theta : 0,
        forwards: item.forwards !== false,
        maxSpeed: isNum(item.maxSpeed) ? item.maxSpeed : DEFAULT_MAX_SPEED,
        lead: isNum(item.lead) ? item.lead : DEFAULT_LEAD,
      });
    }
    const timeout = isNum(data.timeout) && data.timeout > 0 ? data.timeout : DEFAULT_TIMEOUT;
    return { points, timeout };
  } catch {
    return null;
  }
}
