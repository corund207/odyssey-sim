// Path planner data model: pure functions with no DOM access, so the
// C++ generator and the simulator program builder can be tested headlessly.

import type { Chassis } from '../lib/chassis.ts';

export interface PathPoint {
  x: number;
  y: number;
  /** how the robot reaches this point (ignored for the start point) */
  kind: 'point' | 'pose';
  /** arrival heading, compass degrees (start heading for the first point) */
  theta: number;
  forwards: boolean;
  maxSpeed: number;
  /** moveToPose carrot aggressiveness, 0 to 1 (pose points only) */
  lead: number;
}

export const DEFAULT_LEAD = 0.6;
export const DEFAULT_MAX_SPEED = 127;
export const DEFAULT_TIMEOUT = 4000;
export const FIELD_HALF = 72;

export function newPoint(x: number, y: number): PathPoint {
  return {
    x, y, kind: 'point', theta: 0, forwards: true,
    maxSpeed: DEFAULT_MAX_SPEED, lead: DEFAULT_LEAD,
  };
}

/** compass heading (degrees, 0 = +y, clockwise) of the segment from one point to another */
export function bearing(from: { x: number; y: number }, to: { x: number; y: number }): number {
  return wrapHeading(Math.round((Math.atan2(to.x - from.x, to.y - from.y) * 180) / Math.PI));
}

export function clampField(v: number): number {
  return Math.max(-FIELD_HALF, Math.min(FIELD_HALF, v));
}

/** snap to a half-inch so the generated code has clean coordinates */
export function snap(v: number): number {
  return Math.round(v * 2) / 2;
}

/** normalize a compass heading to [0, 360) */
export function wrapHeading(deg: number): number {
  return ((deg % 360) + 360) % 360;
}

export function fmt(n: number): string {
  const r = Math.round(n * 10) / 10;
  return Number.isInteger(r) ? String(r) : r.toFixed(1);
}

export function generateCpp(points: PathPoint[], timeout: number): string {
  if (points.length === 0) {
    return '// Click the field to add waypoints.\n// The C++ for your path appears here.';
  }

  const [start, ...rest] = points;
  const lines: string[] = [
    '// Path generated by Odyssey Simulator',
    `// ${points.length} waypoint${points.length === 1 ? '' : 's'}, ${fmt(pathLength(points))}" of travel`,
    '',
    `chassis.setPose(${fmt(start.x)}, ${fmt(start.y)}, ${fmt(start.theta)});`,
  ];

  for (const p of rest) {
    lines.push('');
    const params: string[] = [];
    if (!p.forwards) params.push('.forwards = false');
    if (p.kind === 'pose' && p.lead !== DEFAULT_LEAD) params.push(`.lead = ${fmt(p.lead)}`);
    if (p.maxSpeed !== DEFAULT_MAX_SPEED) params.push(`.maxSpeed = ${fmt(p.maxSpeed)}`);
    const paramStr = params.length > 0 ? `, {${params.join(', ')}}` : '';

    if (p.kind === 'pose') {
      lines.push(
        `chassis.moveToPose(${fmt(p.x)}, ${fmt(p.y)}, ${fmt(p.theta)}, ${timeout}${paramStr});`,
      );
    } else {
      lines.push(`chassis.moveToPoint(${fmt(p.x)}, ${fmt(p.y)}, ${timeout}${paramStr});`);
    }
    lines.push('chassis.waitUntilDone();');
  }

  return lines.join('\n');
}

/** the same path as a runnable simulator program */
export function buildProgram(
  points: PathPoint[], timeout: number,
): (chassis: Chassis) => Promise<void> {
  const snapshot = points.map((p) => ({ ...p }));
  return async (chassis: Chassis) => {
    const [start, ...rest] = snapshot;
    chassis.setPose(start.x, start.y, start.theta);
    for (const p of rest) {
      if (p.kind === 'pose') {
        const params = { forwards: p.forwards, maxSpeed: p.maxSpeed, lead: p.lead };
        await chassis.moveToPose(p.x, p.y, p.theta, timeout, params, false);
      } else {
        const params = { forwards: p.forwards, maxSpeed: p.maxSpeed };
        await chassis.moveToPoint(p.x, p.y, timeout, params, false);
      }
    }
  };
}

/** total straight-line travel between consecutive waypoints, inches */
export function pathLength(points: PathPoint[]): number {
  let total = 0;
  for (let i = 1; i < points.length; i++) {
    total += Math.hypot(points[i].x - points[i - 1].x, points[i].y - points[i - 1].y);
  }
  return total;
}

/**
 * Reflect a path across the field's vertical (x -> -x) or horizontal
 * (y -> -y) centerline, e.g. to reuse a red-alliance route on blue.
 * Compass headings mirror as -theta (across x) and 180 - theta (across y).
 */
export function mirrorPoints(points: PathPoint[], axis: 'x' | 'y'): PathPoint[] {
  return points.map((p) => ({
    ...p,
    x: axis === 'x' ? -p.x : p.x,
    y: axis === 'y' ? -p.y : p.y,
    theta: wrapHeading(axis === 'x' ? -p.theta : 180 - p.theta),
  }));
}

